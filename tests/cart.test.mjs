import {test, beforeEach} from 'node:test';
import assert from 'node:assert/strict';
import {createPinia,setActivePinia} from 'pinia';
import {nextTick} from 'vue';
import {useCartStore} from '../src/stores/cart.ts';
import {formatCurrency,titleCase} from '../src/utils/format.ts';
const product={id:1,title:'Test',price:10,category:'beauty'};
let data;
beforeEach(()=>{data=new Map();globalThis.localStorage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)};setActivePinia(createPinia());});
test('TC01 empty totals',()=>{const c=useCartStore();assert.equal(c.grandTotal,0);assert.equal(c.totalItems,0)});
test('TC02 add new',()=>{const c=useCartStore();c.addToCart(product);assert.equal(c.grandTotal,22);assert.equal(c.isCartOpen,true)});
test('TC03 add duplicate',()=>{const c=useCartStore();c.addToCart(product);c.addToCart(product);assert.equal(c.items.length,1);assert.equal(c.totalItems,2);assert.equal(c.grandTotal,32)});
test('TC04 decrease two to one',()=>{const c=useCartStore();c.addToCart(product);c.addToCart(product);c.decreaseQuantity(1);assert.equal(c.totalItems,1)});
test('TC05 decrease one to zero',()=>{const c=useCartStore();c.addToCart(product);c.decreaseQuantity(1);assert.equal(c.grandTotal,0)});
test('TC06 unknown ID',()=>{const c=useCartStore();c.decreaseQuantity(99);assert.equal(c.totalItems,0)});
test('TC07 clear',()=>{const c=useCartStore();c.addToCart(product);c.clearCart();assert.equal(c.totalItems,0)});
test('TC08 persistence',async()=>{const c=useCartStore();c.addToCart(product);await nextTick();setActivePinia(createPinia());assert.equal(useCartStore().totalItems,1)});
test('TC09 invalid stored object',()=>{data.set('mini-shop-cart','{}');assert.equal(useCartStore().totalItems,0)});
test('TC10 invalid stored quantity',()=>{data.set('mini-shop-cart',JSON.stringify([{...product,quantity:-1}]));assert.equal(useCartStore().totalItems,0)});
test('TC11 formatting',()=>{assert.equal(formatCurrency(12),'$12.00');assert.equal(titleCase('skin-care'),'Skin Care')});
test('TC12 cart controls',()=>{const c=useCartStore();c.openCart();c.closeCart();assert.equal(c.isCartOpen,false);c.toggleCart();assert.equal(c.isCartOpen,true)});
